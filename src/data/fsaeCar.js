const wheel = [
  ".::::::::.",
  ".:@@@@@@@@@@@@:.",
  ".:@@@@%%%%%%%%@@@@:.",
  ":@@@@%%********%%@@@@:",
  ":@@@%%**(:**:)**%%@@@:",
  ":@@@%%*:(%%%%):*%%@@@:",
  ":@@@%%*:(%%%%):*%%@@@:",
  ":@@@%%**(:**:)**%%@@@:",
  ":@@@@%%********%%@@@@:",
  ".:@@@@%%%%%%%%@@@@:.",
  "':@@@@@@@@@@@@:'",
  "'::::::::'",
];

const wheelWidth = Math.max(...wheel.map(row => row.length));
const lowerBody = wheel.map((row, index) => {
  const line = Array(152).fill(" ");
  const fill = (start, end, symbol) => line.fill(symbol, start, end);
  if (index < 8) {
    fill(Math.min(7, 3 + index), 39, index < 3 ? "%" : "*");
    fill(63, 100, index < 3 ? ":" : index < 6 ? "%" : "*");
    fill(100, 102, "@");
    fill(102, 119, index < 6 ? "%" : "*");
    fill(143, 149, index < 6 ? "%" : "*");
    if (index >= 3 && index < 7) fill(7, 34, "%");
  }
  const centered = row.padStart((wheelWidth + row.length) / 2).padEnd(wheelWidth);
  for (const start of [40, 120]) {
    for (let column = 0; column < wheelWidth; column++) {
      line[start + column] = centered[column];
    }
  }
  return line.join("").trimEnd();
});

const rows = [...upperBody, ...lowerBody];
export const CAR_COLUMNS = Math.max(...rows.map(row => row.length));
export const CAR_ROWS = rows.length;
export const CAR_LETTER_SPACING = 0.12;
export const CAR_LINE_HEIGHT = 1.4;
export default rows.map(row => row.padEnd(CAR_COLUMNS)).join("\n");
